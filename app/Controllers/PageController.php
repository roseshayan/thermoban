    public function submitContact(): void {
        $token = $_POST['csrf_token'] ?? '';
        if (!Security::verifyCsrf($token)) {
            $this->json(['success' => false, 'message' => 'توکن امنیتی نامعتبر است.'], 403);
            return;
        }

        $name = trim($_POST['name'] ?? '');
        $phone = trim($_POST['phone'] ?? '');
        $message = trim($_POST['message'] ?? '');
        $district = trim($_POST['district'] ?? '');

        if (empty($name) || empty($phone)) {
            $this->json(['success' => false, 'message' => 'لطفاً نام و شماره تلفن خود را وارد فرمایید.'], 422);
            return;
        }

        try {
            \App\Models\ContactMessage::create([
                'name'       => $name,
                'phone'      => $phone,
                'district'   => $district,
                'service'    => trim($_POST['service'] ?? 'تعمیر پکیج'),
                'message'    => $message,
                'status'     => 'unread',
                'created_at' => date('Y-m-d H:i:s')
            ]);
        } catch (\Throwable $e) {
            error_log("Failed to insert contact message: " . $e->getMessage());
        }

        $this->json([
            'success' => true,
            'message' => 'پیام شما با موفقیت دریافت شد. کارشناسان ما به زودی با شما تماس خواهند گرفت.'
        ]);
    }
